/**
 * Keep `runtime/*.mjs` copies identical to their `@ruvyxa/core` sources.
 *
 * `serverless-handler.mjs` and its neighbours are copied into a deployed
 * function directory where no bare specifier resolves, so they cannot
 * `import '@ruvyxa/core/route-match'` directly. A copy next to them keeps the
 * deployment self-contained without letting the handler grow a second port of
 * rules that must not disagree.
 *
 * The copies are committed rather than generated at build time, for two
 * reasons that were both real failures:
 *
 *   - `adapter-runner.mjs` imports the handler, and the Rust test suite executes
 *     the adapter runner. CI runs `cargo test` before `pnpm -r build`, so a
 *     generated-only file does not exist yet and the tests fail on a missing
 *     module.
 *   - The files are listed in the package's `files`. Publishing without a build
 *     step having run would ship a tarball whose handler throws on its first
 *     request.
 *
 * Being committed, they can drift from their sources. `--check` is what stops
 * that: `ruvyxa`'s build runs it, so editing a source without regenerating
 * fails the build with the command to fix it, rather than shipping two
 * implementations that disagree — the exact defect this arrangement prevents.
 *
 * Usage:
 *   node scripts/sync-shared-runtime.mjs           regenerate the copies
 *   node scripts/sync-shared-runtime.mjs --check   fail if a copy is stale
 */

import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Every module copied from `@ruvyxa/core` into `runtime/`.
 *
 * `why` is printed when a copy is stale, so the failure says what breaks
 * rather than only which file moved.
 */
const SYNCED_MODULES = [
  {
    specifier: '@ruvyxa/core/route-match',
    source: 'packages/@ruvyxa/core/src/route-match.ts',
    file: 'route-match.mjs',
    why:
      'It is the copy of @ruvyxa/core/route-match that ships inside serverless\n' +
      'function bundles. Letting it drift means the browser router and the\n' +
      'deployed handler can resolve the same URL to different routes.',
  },
  {
    specifier: '@ruvyxa/core/plugin-registration',
    source: 'packages/@ruvyxa/core/src/plugin-registration.ts',
    file: 'plugin-registration.mjs',
    why:
      'It is the copy of @ruvyxa/core/plugin-registration that ships inside\n' +
      'serverless function bundles. Letting it drift means a plugin passes the\n' +
      'harness that validates it and is refused by the server that runs it --\n' +
      'which had already happened: the harness accepted an http.route() on a\n' +
      'reserved framework path that the runtime rejects.',
  },
  {
    specifier: '@ruvyxa/core/origin-policy',
    source: 'packages/@ruvyxa/core/src/origin-policy.ts',
    file: 'origin-policy.mjs',
    why:
      'It is the copy of @ruvyxa/core/origin-policy that ships inside serverless\n' +
      'function bundles. Letting it drift means the action endpoint accepts a\n' +
      'cross-site request that the plugin and the native server both reject.',
  },
]

const require = createRequire(import.meta.url)
const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const checkOnly = process.argv.includes('--check')

function banner(entry) {
  return (
    `// GENERATED by scripts/sync-shared-runtime.mjs from ${entry.specifier}.\n` +
    `// Do not edit: edit ${entry.source} instead, then run\n` +
    '// `pnpm --filter ruvyxa sync:runtime`.\n'
  )
}

function resolveCompiled(entry) {
  try {
    return require.resolve(entry.specifier)
  } catch (error) {
    throw new Error(
      `Cannot resolve ${entry.specifier}. Build @ruvyxa/core first ` +
        '(`pnpm --filter @ruvyxa/core build`), then re-run this script.',
      { cause: error },
    )
  }
}

let stale = 0
for (const entry of SYNCED_MODULES) {
  const source = resolveCompiled(entry)
  const compiled = readFileSync(source, 'utf8')

  // A bare specifier or a Node builtin in the copied output would fail only at
  // request time in a deployed function, so it is rejected here instead.
  const foreignImport = /^\s*(?:import|export)\b[^'"]*from\s+['"]([^'".][^'"]*)['"]/m.exec(compiled)
  if (foreignImport) {
    throw new Error(
      `${entry.specifier} must stay dependency-free; it imports "${foreignImport[1]}". ` +
        'A serverless function bundle resolves no bare specifiers.',
    )
  }

  const destination = path.join(packageRoot, 'runtime', entry.file)
  const expected = `${banner(entry)}${compiled}`

  if (checkOnly) {
    let actual = null
    try {
      actual = readFileSync(destination, 'utf8')
    } catch {
      // Falls through to the same failure as a stale file.
    }
    if (actual !== expected) {
      stale += 1
      console.error(
        `runtime/${entry.file} ${actual === null ? 'is missing' : 'is out of date'}.\n\n` +
          `${entry.why}\n\nRegenerate and commit it:\n\n  pnpm --filter ruvyxa sync:runtime\n`,
      )
    }
    continue
  }

  mkdirSync(path.dirname(destination), { recursive: true })
  writeFileSync(destination, expected, 'utf8')
  console.log(`${entry.file} synced from ${entry.source}`)
}

if (checkOnly) {
  if (stale > 0) process.exit(1)
  console.log(`runtime copies are in sync (${SYNCED_MODULES.length} modules)`)
}
